"""Generate LVGL icon images from the shared HMI icon set.

Source of truth: app/hmi/presentation/icons/svg/*.svg (the web demo embeds the
same files with tools/build_icon_sprite.py). Each icon is rendered at every
size in SIZES as an 8-bit alpha (A8) image. LVGL draws A8 images in the
image's recolour colour, so one bitmap serves every theme role.

Writes:
  app/hmi/presentation/icons/generated/hmi_icons.c
  app/hmi/presentation/icons/include/furnace_hmi/hmi_icons.h

Usage:
    python tools/build_lvgl_icons.py           # regenerate
    python tools/build_lvgl_icons.py --check   # exit 1 if stale

Needs resvg-py and Pillow. Builds do not: the generated files are committed.
"""

from __future__ import annotations

import argparse
import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICON_DIR = ROOT / "app" / "hmi" / "presentation" / "icons"
SVG_DIR = ICON_DIR / "svg"
SOURCE = ICON_DIR / "generated" / "hmi_icons.c"
HEADER = ICON_DIR / "include" / "furnace_hmi" / "hmi_icons.h"
# Pixel sizes used by the web demo: device tags, rails, buttons, icon-only buttons.
SIZES = (16, 18, 20, 22)
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def icons() -> list[Path]:
    paths = sorted(SVG_DIR.glob("*.svg"))
    for path in paths:
        if not NAME.match(path.stem):
            raise SystemExit(f"{path.name}: icon names are lower-case and hyphenated")
    return paths


def render_alpha(svg: str, size: int) -> bytes:
    import resvg_py
    from PIL import Image

    # Icons draw in currentColor; render opaque white and keep only coverage.
    png = resvg_py.svg_to_bytes(svg_string=svg.replace("currentColor", "#ffffff"),
                                width=size, height=size, skip_system_fonts=True)
    image = Image.open(io.BytesIO(bytes(png))).convert("RGBA")
    if image.size != (size, size):
        raise SystemExit(f"rendered {image.size}, expected {size}x{size}")
    return image.getchannel("A").tobytes()


def symbol(stem: str) -> str:
    return stem.replace("-", "_")


def header_text(paths: list[Path]) -> str:
    enumerators = "\n".join(
        f"    FURNACE_HMI_ICON_{symbol(path.stem).upper()}," for path in paths
    )
    sizes = ", ".join(str(size) for size in SIZES)
    return f"""/* SPDX-License-Identifier: Apache-2.0 */
/* Generated by tools/build_lvgl_icons.py from icons/svg; do not edit. */

#ifndef FURNACE_HMI_HMI_ICONS_H
#define FURNACE_HMI_HMI_ICONS_H

#include <stdint.h>

#include <lvgl.h>

#ifdef __cplusplus
extern "C" {{
#endif

typedef enum {{
{enumerators}
    FURNACE_HMI_ICON_COUNT,
}} furnace_hmi_icon_t;

/**
 * The icon as an 8-bit alpha image of `size` x `size` pixels, drawn in the
 * image recolour colour. Generated sizes: {sizes}. Returns NULL for any other
 * size or an out-of-range icon.
 */
const lv_image_dsc_t *furnace_hmi_icon_image(furnace_hmi_icon_t icon, int32_t size);

#ifdef __cplusplus
}}
#endif

#endif /* FURNACE_HMI_HMI_ICONS_H */
"""


def source_text(paths: list[Path]) -> str:
    parts = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Generated by tools/build_lvgl_icons.py from icons/svg; do not edit. */",
        "",
        "#include <furnace_hmi/hmi_icons.h>",
        "",
    ]
    table_rows = []
    for path in paths:
        svg = path.read_text(encoding="utf-8")
        row = []
        for size in SIZES:
            name = f"icon_{symbol(path.stem)}_{size}"
            data = render_alpha(svg, size)
            lines = []
            for offset in range(0, len(data), size):
                lines.append("    " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + size]) + ",")
            parts += [
                f"static const uint8_t {name}_map[] = {{",
                *lines,
                "};",
                "",
                f"static const lv_image_dsc_t {name} = {{",
                "    .header = {",
                "        .magic = LV_IMAGE_HEADER_MAGIC,",
                "        .cf = LV_COLOR_FORMAT_A8,",
                f"        .w = {size},",
                f"        .h = {size},",
                f"        .stride = {size},",
                "    },",
                f"    .data_size = sizeof({name}_map),",
                f"    .data = {name}_map,",
                "};",
                "",
            ]
            row.append(f"&{name}")
        table_rows.append("    { " + ", ".join(row) + " },")
    sizes = ", ".join(str(size) for size in SIZES)
    parts += [
        f"static const int32_t icon_sizes[{len(SIZES)}] = {{ {sizes} }};",
        "",
        f"static const lv_image_dsc_t *const icon_table[FURNACE_HMI_ICON_COUNT][{len(SIZES)}] = {{",
        *table_rows,
        "};",
        "",
        "const lv_image_dsc_t *furnace_hmi_icon_image(furnace_hmi_icon_t icon, int32_t size)",
        "{",
        "    if ((int)icon < 0 || icon >= FURNACE_HMI_ICON_COUNT) {",
        "        return NULL;",
        "    }",
        f"    for (int index = 0; index < {len(SIZES)}; ++index) {{",
        "        if (icon_sizes[index] == size) {",
        "            return icon_table[icon][index];",
        "        }",
        "    }",
        "    return NULL;",
        "}",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when generated files are stale")
    arguments = parser.parse_args()
    paths = icons()
    outputs = {HEADER: header_text(paths).encode("utf-8"), SOURCE: source_text(paths).encode("utf-8")}
    if arguments.check:
        stale = [path for path, data in outputs.items() if not path.exists() or path.read_bytes() != data]
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    for path, data in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
