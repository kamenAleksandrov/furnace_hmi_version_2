"""Generate the HMI typeface (Tomorrow HMI) for LVGL and the web demo.

Source of truth: app/hmi/presentation/fonts/source/TomorrowHMI-*.ttf, made by
--import-tomorrow from the upstream Tomorrow release (SIL OFL 1.1, no Reserved
Font Name): subset to the HMI character set, digits given one common width
(our modified version; readings no longer shift as they change) and the family
renamed "Tomorrow HMI". From them this tool writes

  * one LVGL C font per (weight, size) in FACES, into fonts/generated/,
  * fonts/include/furnace_hmi/hmi_fonts.h declaring them,
  * an embedded @font-face block between the hmi-fonts markers of the web demo,

so both presentations draw the same glyphs.

Usage:
    python tools/build_fonts.py --import-tomorrow DIR  # refresh sources from
        # a folder with Tomorrow-Medium.ttf, Tomorrow-SemiBold.ttf and OFL.txt
        # (github.com/google/fonts/tree/main/ofl/tomorrow)
    python tools/build_fonts.py                               # regenerate
    python tools/build_fonts.py --check                       # exit 1 if stale

Needs fontTools and brotli (Python) and Node's npx for lv_font_conv. Builds do
not: the generated files are committed.
"""

from __future__ import annotations

import argparse
import base64
import copy
import io
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "app" / "hmi" / "presentation" / "fonts"
SOURCE_DIR = FONT_DIR / "source"
GENERATED_DIR = FONT_DIR / "generated"
HEADER = FONT_DIR / "include" / "furnace_hmi" / "hmi_fonts.h"
WEB_PAGES = [ROOT / "docs" / "images" / "theme" / "hmi-web-demo.html"]
WEB_BEGIN = "/* hmi-fonts:begin (generated by tools/build_fonts.py; do not edit) */"
WEB_END = "/* hmi-fonts:end */"

LV_FONT_CONV = "lv_font_conv@1.5.2"
# ASCII plus the few symbols the HMI text uses: degree, middle dot,
# multiplication, en/em dash, ellipsis and single guillemets. Arrows are icons.
RANGES = "0x20-0x7E,0xB0,0xB7,0xD7,0x2013,0x2014,0x2026,0x2039,0x203A"
UNICODES = [*range(0x20, 0x7F), 0xB0, 0xB7, 0xD7, 0x2013, 0x2014, 0x2026, 0x2039, 0x203A]
FAMILY = "Tomorrow HMI"

# Roles, not upstream weights: the body text ("regular", CSS 400/500) uses
# Tomorrow Medium, because LVGL's unhinted 4 bpp rendering draws Tomorrow
# Regular too thin on the panel; strong text uses SemiBold (CSS 600/700).
WEIGHTS = {"regular": ("TomorrowHMI-Medium.ttf", 400), "semibold": ("TomorrowHMI-SemiBold.ttf", 600)}
UPSTREAM = {"regular": ("Tomorrow-Medium.ttf", "Medium"), "semibold": ("Tomorrow-SemiBold.ttf", "SemiBold")}
# Sizes follow the web demo's type scale (see LVGL_SOFT_TILE_PORT_PLAN.md).
FACES = {
    # 400 and 500 in the web CSS (Chrome on Windows renders 500 as regular).
    "regular": [12, 13, 14, 15, 16, 18, 19, 20, 22, 23, 24, 36],
    # 600 and 700: important and selected actions, headings, stage kinds.
    "semibold": [12, 13, 14, 15, 16, 18, 19, 20, 22, 24, 26, 48],
}


def font_name(weight: str, size: int) -> str:
    return f"furnace_hmi_font_{weight}_{size}"


def tabular_digits(font) -> None:
    """Give 0-9 one advance width, centring each outline in it.

    The digits are copied to new glyphs (`zero.tf` ...) and the character map
    points at the copies: kerning still names the originals, so no pair can
    move a digit, and subsetting drops the unused originals."""
    cmap = font.getBestCmap()
    glyf, hmtx = font["glyf"], font["hmtx"]
    originals = [cmap[ord(digit)] for digit in "0123456789"]
    width = max(hmtx[name][0] for name in originals)
    order = list(font.getGlyphOrder())
    renamed = {}
    for name in originals:
        copy_name = f"{name}.tf"
        glyph = copy.deepcopy(glyf[name])
        advance, lsb = hmtx[name]
        shift = (width - advance) // 2
        if glyph.isComposite():
            for component in glyph.components:
                component.x += shift
        elif glyph.numberOfContours > 0:
            glyph.coordinates.translate((shift, 0))
        order.append(copy_name)
        font.setGlyphOrder(order)
        glyf.glyphOrder = order
        glyf[copy_name] = glyph
        glyph.recalcBounds(glyf)
        hmtx[copy_name] = (width, glyph.xMin if glyph.numberOfContours else lsb + shift)
        renamed[name] = copy_name
    for table in font["cmap"].tables:
        for code, name in list(table.cmap.items()):
            if name in renamed:
                table.cmap[code] = renamed[name]


def rename_family(font, style: str) -> None:
    """Mark the modified version with its own family name (OFL 1.1 permits
    keeping "Tomorrow"; the upstream release reserves no font name)."""
    names = {1: FAMILY, 2: style, 3: f"{FAMILY} {style}; modified by tools/build_fonts.py",
             4: f"{FAMILY} {style}", 6: f"{FAMILY.replace(' ', '')}-{style.replace(' ', '')}",
             16: FAMILY, 17: style}
    table = font["name"]
    for name_id in (1, 2, 3, 4, 6, 16, 17):
        table.removeNames(nameID=name_id)
    for name_id, text in names.items():
        table.setName(text, name_id, 3, 1, 0x409)


def import_tomorrow(folder: Path) -> None:
    from fontTools import subset
    from fontTools.ttLib import TTFont

    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    (FONT_DIR / "OFL.txt").write_bytes((folder / "OFL.txt").read_bytes().replace(b"\r\n", b"\n"))
    for weight, (file_name, _) in WEIGHTS.items():
        upstream_file, style = UPSTREAM[weight]
        font = TTFont(folder / upstream_file)
        tabular_digits(font)
        options = subset.Options()
        options.layout_features = ["kern"]
        options.name_IDs = ["*"]
        options.notdef_outline = True
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=UNICODES)
        subsetter.subset(font)
        rename_family(font, style)
        font.save(SOURCE_DIR / file_name)
        print(f"imported {file_name}")


def npx() -> str:
    command = shutil.which("npx") or shutil.which("npx.cmd")
    if command is None:
        raise SystemExit("npx not found: install Node.js to run lv_font_conv")
    return command


def lvgl_font(weight: str, size: int, destination: Path) -> None:
    file_name, _ = WEIGHTS[weight]
    name = font_name(weight, size)
    subprocess.run(
        [npx(), "--yes", LV_FONT_CONV, "--no-compress", "--no-prefilter", "--bpp", "4",
         "--size", str(size), "--format", "lvgl", "--lv-include", "lvgl.h",
         "--font", file_name, "-r", RANGES,
         "-o", str(destination / f"{name}.c")],
        cwd=SOURCE_DIR, check=True, stdout=subprocess.DEVNULL,
    )
    # lv_font_conv 1.5 names the font after the output file (hence `name`).
    # It writes CRLF on Windows; keep the repository form stable.
    # The Opts header also echoes the scratch output path; keep the file name only.
    path = destination / f"{name}.c"
    text = path.read_bytes().replace(b"\r\n", b"\n")
    path.write_bytes(text.replace(str(path).encode("utf-8"), path.name.encode("utf-8")))


def header_text() -> str:
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Generated by tools/build_fonts.py; do not edit. */",
        "",
        "#ifndef FURNACE_HMI_HMI_FONTS_H",
        "#define FURNACE_HMI_HMI_FONTS_H",
        "",
        "#include <lvgl.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/* Tomorrow HMI, a modified Tomorrow (SIL Open Font License 1.1,",
        " * see fonts/OFL.txt): body text (Medium) and strong text (SemiBold). */",
    ]
    for weight, sizes in FACES.items():
        lines += [f"LV_FONT_DECLARE({font_name(weight, size)})" for size in sizes]
    lines += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif /* FURNACE_HMI_HMI_FONTS_H */", ""]
    return "\n".join(lines)


def web_block() -> str:
    from fontTools.ttLib import TTFont

    rules = [WEB_BEGIN]
    for file_name, css_weight in WEIGHTS.values():
        # Keep the source timestamp so the embedded font is reproducible.
        font = TTFont(SOURCE_DIR / file_name, recalcTimestamp=False)
        font.flavor = "woff2"
        buffer = io.BytesIO()
        font.save(buffer)
        data = base64.b64encode(buffer.getvalue()).decode("ascii")
        rules.append(
            f"@font-face{{font-family:'{FAMILY}';font-style:normal;"
            f"font-weight:{css_weight};font-display:block;"
            f"src:url(data:font/woff2;base64,{data}) format('woff2')}}"
        )
    rules.append(WEB_END)
    return "\n".join(rules)


def embed(page_text: str, block: str) -> str:
    start = page_text.find(WEB_BEGIN)
    end = page_text.find(WEB_END)
    if start < 0 or end < start:
        raise SystemExit("hmi-fonts markers not found in web page")
    return page_text[:start] + block + page_text[end + len(WEB_END):]


def generate(into: Path) -> dict[Path, bytes]:
    """Build every output into a scratch tree; map repository path -> bytes."""
    outputs: dict[Path, bytes] = {}
    generated = into / "generated"
    generated.mkdir(parents=True)
    for weight, sizes in FACES.items():
        for size in sizes:
            lvgl_font(weight, size, generated)
    for path in sorted(generated.glob("*.c")):
        outputs[GENERATED_DIR / path.name] = path.read_bytes()
    outputs[HEADER] = header_text().encode("utf-8")
    block = web_block()
    for page in WEB_PAGES:
        # Decode without newline translation so a CRLF page stays CRLF.
        text = page.read_bytes().decode("utf-8")
        newline = "\r\n" if "\r\n" in text else "\n"
        outputs[page] = embed(text, block.replace("\n", newline)).encode("utf-8")
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--import-tomorrow", type=Path, metavar="DIR",
                        help="make the HMI cut of Tomorrow from an upstream folder into fonts/source")
    parser.add_argument("--check", action="store_true", help="fail when generated files are stale")
    arguments = parser.parse_args()
    if arguments.import_tomorrow is not None:
        import_tomorrow(arguments.import_tomorrow)
    with tempfile.TemporaryDirectory() as scratch:
        outputs = generate(Path(scratch))
    expected_c = {path for path in outputs if path.parent == GENERATED_DIR}
    stale_c = sorted(set(GENERATED_DIR.glob("*.c")) - expected_c) if GENERATED_DIR.exists() else []
    if arguments.check:
        stale = [path for path, data in outputs.items()
                 if not path.exists() or path.read_bytes() != data] + stale_c
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    for path in stale_c:
        path.unlink()
    for path, data in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
