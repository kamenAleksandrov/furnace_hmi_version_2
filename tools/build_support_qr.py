"""Generate the Device info support QR code for both HMI presentations.

Source of truth: app/hmi/presentation/icons/images/support-qr.png (the
product owner's code for SUPPORT_URL, with the logo in the middle). It is
turned into one 8-bit alpha (A8) image: darker source pixels are more opaque.
Both presentations draw it in the theme's `qr-ink` colour on a `qr-plate`
background, so the code stays dark-on-light (scannable) in every theme.

Writes:
  app/hmi/presentation/icons/generated/support_qr.c        (LVGL A8 image)
  app/hmi/presentation/icons/include/furnace_hmi/support_qr.h
  docs/images/theme/hmi-web-demo.html                       (CSS mask, between
                                                             the support-qr markers)

Usage:
    python tools/build_support_qr.py           # regenerate
    python tools/build_support_qr.py --check   # exit 1 if stale
    python tools/build_support_qr.py --verify  # also decode the result (needs OpenCV)

Needs Pillow. Builds do not: the generated files are committed.
"""

from __future__ import annotations

import argparse
import base64
import io
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ICON_DIR = ROOT / "app" / "hmi" / "presentation" / "icons"
IMAGE = ICON_DIR / "images" / "support-qr.png"
SOURCE = ICON_DIR / "generated" / "support_qr.c"
HEADER = ICON_DIR / "include" / "furnace_hmi" / "support_qr.h"
WEB_PAGE = ROOT / "docs" / "images" / "theme" / "hmi-web-demo.html"
SUPPORT_URL = "https://telamorph.com/"
SIZE = 200
WEB_BLOCK = re.compile(r"/\* support-qr:begin.*?/\* support-qr:end \*/", re.DOTALL)


def alpha_map() -> Image.Image:
    """The code as coverage: 255 where the source is darkest, 0 on white."""
    source = Image.open(IMAGE).convert("RGBA")
    plate = Image.new("RGBA", source.size, (255, 255, 255, 255))
    plate.alpha_composite(source)
    luminance = plate.convert("L").resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    values = sorted(luminance.tobytes())
    darkest = values[len(values) // 20]
    span = max(1, 255 - darkest)
    return luminance.point(lambda value: max(0, min(255, round((255 - value) * 255 / span))))


def header_text() -> str:
    return "\n".join([
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Generated by tools/build_support_qr.py from icons/images/support-qr.png; do not edit. */",
        "",
        "#ifndef FURNACE_HMI_SUPPORT_QR_H",
        "#define FURNACE_HMI_SUPPORT_QR_H",
        "",
        "#include <lvgl.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f"/** Support QR code ({SUPPORT_URL}), A8: draw it in qr-ink on a qr-plate background. */",
        "extern const lv_image_dsc_t furnace_hmi_support_qr;",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* FURNACE_HMI_SUPPORT_QR_H */",
        "",
    ])


def source_text(alpha: Image.Image) -> str:
    data = alpha.tobytes()
    rows = ["    " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + SIZE]) + ","
            for offset in range(0, len(data), SIZE)]
    return "\n".join([
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Generated by tools/build_support_qr.py from icons/images/support-qr.png; do not edit. */",
        "",
        "#include <furnace_hmi/support_qr.h>",
        "",
        "static const uint8_t support_qr_map[] = {",
        *rows,
        "};",
        "",
        "const lv_image_dsc_t furnace_hmi_support_qr = {",
        "    .header = {",
        "        .magic = LV_IMAGE_HEADER_MAGIC,",
        "        .cf = LV_COLOR_FORMAT_A8,",
        f"        .w = {SIZE},",
        f"        .h = {SIZE},",
        f"        .stride = {SIZE},",
        "    },",
        "    .data_size = sizeof(support_qr_map),",
        "    .data = support_qr_map,",
        "};",
        "",
    ])


def web_block(alpha: Image.Image) -> str:
    mask = Image.merge("LA", (Image.new("L", alpha.size, 0), alpha))
    buffer = io.BytesIO()
    mask.save(buffer, format="PNG", optimize=True)
    url = "url(data:image/png;base64," + base64.b64encode(buffer.getvalue()).decode("ascii") + ")"
    return ("/* support-qr:begin (generated by tools/build_support_qr.py; do not edit) */\n"
            f"#soft .support-qr-code{{-webkit-mask:{url} center/contain no-repeat;mask:{url} center/contain no-repeat}}\n"
            "/* support-qr:end */")


def verify(alpha: Image.Image) -> bool:
    """Decode the code as drawn (dark ink on a light plate with a quiet zone), also enlarged as a camera sees it."""
    import cv2  # type: ignore[import-not-found]
    import numpy

    drawn = Image.new("L", (SIZE + 48, SIZE + 48), 240)
    drawn.paste(Image.new("L", alpha.size, 24), (24, 24), alpha)
    found = set()
    for factor in (1, 2, 3):
        image = numpy.array(drawn.resize((drawn.width * factor, drawn.height * factor), Image.Resampling.NEAREST))
        for detector in (cv2.QRCodeDetectorAruco(), cv2.QRCodeDetector()):
            found.add(detector.detectAndDecode(image)[0])
    print("decoded:", ", ".join(sorted(value for value in found if value)) or "nothing")
    return SUPPORT_URL in found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when generated files are stale")
    parser.add_argument("--verify", action="store_true", help="decode the generated code (needs OpenCV)")
    arguments = parser.parse_args()
    alpha = alpha_map()
    page = WEB_PAGE.read_text(encoding="utf-8")
    if len(WEB_BLOCK.findall(page)) != 1:
        print("web page: expected one support-qr block")
        return 1
    outputs = {
        HEADER: header_text().encode("utf-8"),
        SOURCE: source_text(alpha).encode("utf-8"),
        WEB_PAGE: WEB_BLOCK.sub(lambda _: web_block(alpha), page).encode("utf-8"),
    }
    if arguments.verify and not verify(alpha):
        print("the generated code does not decode to " + SUPPORT_URL)
        return 1
    if arguments.check:
        stale = [path for path, data in outputs.items() if not path.exists() or path.read_bytes() != data]
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    for path, data in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
