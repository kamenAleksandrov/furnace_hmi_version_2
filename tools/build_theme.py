"""Generate the HMI colour palettes from the shared theme source.

Source of truth: app/hmi/presentation/theme/themes.json (tokens and one colour
per token for every theme). Writes:

  app/hmi/presentation/theme/include/furnace_hmi/hmi_theme.h   colour roles, theme ids
  app/hmi/presentation/theme/generated/hmi_theme.c             palettes
  docs/images/theme/hmi-web-demo.html                          CSS custom properties and
                                                               the theme/token lists, between
                                                               the hmi-theme markers

Usage:
    python tools/build_theme.py           # regenerate
    python tools/build_theme.py --check   # exit 1 if anything is stale or invalid
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEME_DIR = ROOT / "app" / "hmi" / "presentation" / "theme"
SOURCE = THEME_DIR / "themes.json"
HEADER = THEME_DIR / "include" / "furnace_hmi" / "hmi_theme.h"
C_SOURCE = THEME_DIR / "generated" / "hmi_theme.c"
STRING_CATALOGUE = ROOT / "app" / "hmi" / "presentation" / "strings" / "catalogue" / "en.json"
WEB_PAGES = [ROOT / "docs" / "images" / "theme" / "hmi-web-demo.html"]
BEGIN = "<!-- hmi-theme:begin (generated by tools/build_theme.py from app/hmi/presentation/theme/themes.json; do not edit) -->"
END = "<!-- hmi-theme:end -->"
NAME = re.compile(r"^[a-z][a-z0-9]*(-[a-z0-9]+)*$")
HEX = re.compile(r"^#([0-9a-fA-F]{6})$")
RGBA = re.compile(r"^rgba\((\d{1,3}),(\d{1,3}),(\d{1,3}),(0?\.\d+|0|1)\)$")
NOTICE = "Generated by tools/build_theme.py from app/hmi/presentation/theme/themes.json; do not edit."


def fail(message: str) -> None:
    raise SystemExit(f"themes.json: {message}")


def parse_color(token: str, value: str) -> tuple[int, int]:
    """Return (rgb, opa 0-255). Opacity rounds half up, matching LV_OPA_* style values."""
    compact = value.replace(" ", "")
    match = HEX.match(compact)
    if match:
        return int(match.group(1), 16), 255
    match = RGBA.match(compact)
    if match:
        r, g, b = (int(match.group(i)) for i in (1, 2, 3))
        alpha = float(match.group(4))
        if max(r, g, b) > 255 or not 0.0 <= alpha <= 1.0:
            fail(f"{token}: out of range: {value}")
        return (r << 16) | (g << 8) | b, int(alpha * 255 + 0.5)
    fail(f"{token}: expected #rrggbb or rgba(r,g,b,a), got {value!r}")
    raise AssertionError


def load() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    names = [token["name"] for token in data["tokens"]]
    for name in names:
        if not NAME.match(name):
            fail(f"token names are lower-case and hyphenated: {name}")
    if len(set(names)) != len(names):
        fail("duplicate token names")
    strings = set(json.loads(STRING_CATALOGUE.read_text(encoding="utf-8"))["strings"])
    ids = [theme["id"] for theme in data["themes"]]
    if not ids or len(set(ids)) != len(ids):
        fail("themes need unique ids")
    for theme in data["themes"]:
        if not NAME.match(theme["id"]):
            fail(f"theme ids are lower-case and hyphenated: {theme['id']}")
        if theme["name_string"] not in strings:
            fail(f"{theme['id']}: unknown string {theme['name_string']}")
        colors = theme["colors"]
        missing = [name for name in names if name not in colors]
        extra = [name for name in colors if name not in names]
        if missing or extra:
            fail(f"{theme['id']}: missing {missing}, unknown {extra}")
        for name in names:
            parse_color(f"{theme['id']}.{name}", colors[name])
        check_contrast(theme, data.get("contrast", []), names)
    return data


def luminance(rgb: int) -> float:
    channels = [((rgb >> shift) & 0xFF) / 255 for shift in (16, 8, 0)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def check_contrast(theme: dict, pairs: list[dict], names: list[str]) -> None:
    """Fail when text in this theme drops below its WCAG contrast minimum."""
    for pair in pairs:
        if pair["text"] not in names or pair["on"] not in names:
            fail(f"contrast pair uses an unknown token: {pair}")
        text, text_opa = parse_color(pair["text"], theme["colors"][pair["text"]])
        background, background_opa = parse_color(pair["on"], theme["colors"][pair["on"]])
        if text_opa != 255 or background_opa != 255:
            fail(f"contrast pairs need opaque colours: {pair}")
        high, low = sorted((luminance(text), luminance(background)), reverse=True)
        ratio = (high + 0.05) / (low + 0.05)
        if ratio < pair["min"]:
            fail(f"{theme['id']}: {pair['text']} on {pair['on']} has contrast {ratio:.2f}, needs {pair['min']}")


def c_name(name: str) -> str:
    return name.replace("-", "_").upper()


def header(data: dict) -> str:
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        f"/* {NOTICE} */",
        "",
        "#ifndef FURNACE_HMI_HMI_THEME_H",
        "#define FURNACE_HMI_HMI_THEME_H",
        "",
        "#include <stdint.h>",
        "",
        "#include <furnace_hmi/ui_strings.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/** Colour roles. Every theme defines every role; see themes.json for each role's use. */",
        "typedef enum {",
    ]
    for index, token in enumerate(data["tokens"]):
        suffix = " = 0" if index == 0 else ""
        lines.append(f"    FURNACE_HMI_COLOR_{c_name(token['name'])}{suffix}, /**< {token['doc']} */")
    lines += [
        "    FURNACE_HMI_COLOR_COUNT",
        "} furnace_hmi_color_role_t;",
        "",
        "/** Available themes; the first is the default. */",
        "typedef enum {",
    ]
    for index, theme in enumerate(data["themes"]):
        suffix = " = 0" if index == 0 else ""
        lines.append(f"    FURNACE_HMI_THEME_{c_name(theme['id'])}{suffix},")
    lines += [
        "    FURNACE_HMI_THEME_COUNT",
        "} furnace_hmi_theme_id_t;",
        "",
        "/** One colour with its own opacity (255 is opaque). */",
        "typedef struct {",
        "    uint32_t rgb;",
        "    uint8_t opa;",
        "} furnace_hmi_color_t;",
        "",
        "typedef struct {",
        "    const char *id;                    /**< Stable id; also the web data-hmi-theme value. */",
        "    furnace_hmi_ui_string_id_t name;   /**< Display name. */",
        "    const furnace_hmi_color_t *colors; /**< FURNACE_HMI_COLOR_COUNT entries. */",
        "} furnace_hmi_theme_t;",
        "",
        "/** Return a theme, or NULL for an invalid identifier. */",
        "const furnace_hmi_theme_t *furnace_hmi_theme(furnace_hmi_theme_id_t id);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* FURNACE_HMI_HMI_THEME_H */",
        "",
    ]
    return "\n".join(lines)


def c_source(data: dict) -> str:
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        f"/* {NOTICE} */",
        "",
        "#include <stddef.h>",
        "",
        "#include <furnace_hmi/hmi_theme.h>",
        "",
    ]
    for theme in data["themes"]:
        lines.append(f"static const furnace_hmi_color_t {c_name(theme['id']).lower()}_colors[FURNACE_HMI_COLOR_COUNT] = {{")
        for token in data["tokens"]:
            rgb, opa = parse_color(token["name"], theme["colors"][token["name"]])
            lines.append(f"    [FURNACE_HMI_COLOR_{c_name(token['name'])}] = {{ 0x{rgb:06X}U, {opa}U }},")
        lines += ["};", ""]
    lines.append("static const furnace_hmi_theme_t themes[FURNACE_HMI_THEME_COUNT] = {")
    for theme in data["themes"]:
        lines.append(f"    [FURNACE_HMI_THEME_{c_name(theme['id'])}] = {{")
        lines.append(f"        \"{theme['id']}\", FURNACE_HMI_UI_STRING_{theme['name_string']}, {c_name(theme['id']).lower()}_colors,")
        lines.append("    },")
    lines += [
        "};",
        "",
        "const furnace_hmi_theme_t *furnace_hmi_theme(furnace_hmi_theme_id_t id)",
        "{",
        "    if ((int)id < 0 || id >= FURNACE_HMI_THEME_COUNT) {",
        "        return NULL;",
        "    }",
        "    return &themes[id];",
        "}",
        "",
    ]
    return "\n".join(lines)


def css_value(value: str) -> str:
    compact = value.replace(" ", "")
    return compact.lower() if compact.startswith("#") else compact


def web_block(data: dict) -> str:
    def declarations(theme: dict) -> str:
        return ";".join(f"--{token['name']}:{css_value(theme['colors'][token['name']])}" for token in data["tokens"])

    # The first theme is the default; each theme also answers to its data-hmi-theme value.
    rules = [f"#soft{{{declarations(data['themes'][0])}}}"]
    rules += [f"#soft[data-hmi-theme='{theme['id']}']{{{declarations(theme)}}}" for theme in data["themes"]]
    themes = ",".join(f"{{id:'{theme['id']}',name:'{theme['name_string']}'}}" for theme in data["themes"])
    tokens = ",".join(f"'{token['name']}'" for token in data["tokens"])
    return "\n".join([
        BEGIN,
        "<style id='hmi-theme-tokens'>",
        *rules,
        "</style>",
        "<script id='hmi-theme-data'>",
        f"const HMI_THEMES=[{themes}];",
        f"const HMI_THEME_TOKENS=[{tokens}];",
        "</script>",
        END,
    ])


def write(path: Path, text: str, check: bool, stale: list[Path]) -> None:
    current = path.read_bytes().decode("utf-8") if path.exists() else None
    if current == text:
        return
    if check:
        stale.append(path)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    print(f"wrote {path.relative_to(ROOT)}")


def update_page(path: Path, block: str, check: bool, stale: list[Path]) -> None:
    page = path.read_bytes().decode("utf-8")
    start, end = page.find(BEGIN), page.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{path.relative_to(ROOT)}: hmi-theme markers not found")
    updated = page[:start] + block + page[end + len(END):]
    write(path, updated, check, stale)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    data = load()
    stale: list[Path] = []
    write(HEADER, header(data), args.check, stale)
    write(C_SOURCE, c_source(data), args.check, stale)
    block = web_block(data)
    for page in WEB_PAGES:
        update_page(page, block, args.check, stale)
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
