"""Generate the HMI string catalogue for both presentations.

Source of truth: app/hmi/presentation/strings/catalogue/<tag>.json, one file
per language. en.json is the default and the fallback and defines every
string identifier; other languages translate any subset (missing strings fall
back to English). Writes:

  app/hmi/presentation/strings/include/furnace_hmi/ui_string_ids.h   string and language ids
  app/hmi/presentation/strings/generated/ui_strings_catalogue.c      C tables
  docs/images/theme/hmi-web-demo.html                                 the same catalogue for the
                                                                      web demo (hmi-strings markers)

Checks: identifiers, empty texts, translations of unknown ids, printf
conversions (a translation keeps the English conversions in the same order),
pattern fields (the same {names}, any order), the one-character decimal
separator, and characters the HMI font cannot draw (tools/build_fonts.py
glyph set).

Text syntax: printf conversions as in C. An <inttypes.h> conversion is written
%<PRIi32> (with flags and width before the macro: %02<PRIi32>). Patterns
(ids ending in _PATTERN) use {name} fields that a language may reorder.

Usage:
    python tools/build_strings.py           # regenerate
    python tools/build_strings.py --check   # exit 1 if anything is stale or invalid
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRINGS_DIR = ROOT / "app" / "hmi" / "presentation" / "strings"
CATALOGUE_DIR = STRINGS_DIR / "catalogue"
HEADER = STRINGS_DIR / "include" / "furnace_hmi" / "ui_string_ids.h"
C_SOURCE = STRINGS_DIR / "generated" / "ui_strings_catalogue.c"
WEB_PAGES = [ROOT / "docs" / "images" / "theme" / "hmi-web-demo.html"]
BEGIN = "<!-- hmi-strings:begin (generated by tools/build_strings.py from app/hmi/presentation/strings/catalogue; do not edit) -->"
END = "<!-- hmi-strings:end -->"
NOTICE = "Generated by tools/build_strings.py from app/hmi/presentation/strings/catalogue; do not edit."
DEFAULT = "en"
ID = re.compile(r"^[A-Z][A-Z0-9_]*$")
TAG = re.compile(r"^[a-z]{2,3}(-[A-Z]{2})?$")
FIELD = re.compile(r"\{([a-z]+)\}")
CONVERSION = re.compile(r"%(%|[-+ #0]*\d*(?:\.\d+)?(?:(?:hh|h|ll|l|j|z|t)?[diouxXcsfFeEgGp]|<PRI[a-zA-Z0-9]+>))")


def fail(message: str) -> None:
    raise SystemExit(f"strings catalogue: {message}")


def conversions(text: str) -> list[str]:
    """The printf argument conversions of a text, ignoring flags and widths."""
    found = []
    for match in CONVERSION.finditer(text):
        spec = match.group(1)
        if spec == "%":
            continue
        macro = re.search(r"<(PRI[a-zA-Z0-9]+)>", spec)
        found.append(macro.group(1) if macro else spec[-1])
    return found


def font_glyphs() -> set[int]:
    sys.path.insert(0, str(ROOT / "tools"))
    from build_fonts import UNICODES  # stdlib-only at import time
    return set(UNICODES) | {ord("\n")}


def load() -> list[dict]:
    paths = sorted(CATALOGUE_DIR.glob("*.json"), key=lambda p: (p.stem != DEFAULT, p.stem))
    if not paths or paths[0].stem != DEFAULT:
        fail(f"{DEFAULT}.json is required")
    languages = []
    for path in paths:
        data = json.loads(path.read_text(encoding="utf-8"))
        tag = data["language"]["tag"]
        if tag != path.stem or not TAG.match(tag):
            fail(f"{path.name}: language tag must match the file name ({tag})")
        if not data["language"].get("name"):
            fail(f"{path.name}: language name (autonym) is required")
        languages.append({"tag": tag, "name": data["language"]["name"],
                          "strings": data["strings"], "notes": data.get("notes", {}), "path": path})
    english = languages[0]["strings"]
    for key, text in english.items():
        if not ID.match(key):
            fail(f"en.json: invalid identifier {key}")
        if not isinstance(text, str) or text == "":
            fail(f"en.json: {key} is empty")
    for note in languages[0]["notes"]:
        if note not in english:
            fail(f"en.json: note for unknown identifier {note}")
    glyphs = font_glyphs()
    for language in languages:
        for key, text in language["strings"].items():
            if key not in english:
                fail(f"{language['path'].name}: unknown identifier {key}")
            if not isinstance(text, str) or text == "":
                fail(f"{language['path'].name}: {key} is empty")
            if conversions(text) != conversions(english[key]):
                fail(f"{language['path'].name}: {key} must keep the conversions {conversions(english[key])} "
                     f"in order, has {conversions(text)}")
            if sorted(FIELD.findall(text)) != sorted(FIELD.findall(english[key])):
                fail(f"{language['path'].name}: {key} must keep the pattern fields "
                     f"{sorted(FIELD.findall(english[key]))} (any order)")
            if key == "UI_LAB_DECIMAL_SEPARATOR" and (len(text) != 1 or not text.isascii()):
                fail(f"{language['path'].name}: {key} must be one ASCII character")
            missing = sorted({ch for ch in text if ord(ch) not in glyphs})
            if missing:
                fail(f"{language['path'].name}: {key} uses characters the HMI font cannot draw: "
                     + " ".join(f"U+{ord(ch):04X}" for ch in missing))
        missing = sorted({ch for ch in language["name"] if ord(ch) not in glyphs})
        if missing:
            fail(f"{language['path'].name}: language name uses characters the HMI font cannot draw")
    return languages


def c_literal(text: str) -> str:
    """ASCII C string literal(s); <PRI..> markers become inttypes macros."""
    pieces = []
    for part in re.split(r"(<PRI[a-zA-Z0-9]+>)", text):
        if part.startswith("<PRI"):
            pieces.append(part[1:-1])
            continue
        if part == "":
            continue
        out, literal, after_hex = [], [], False
        for byte in part.encode("utf-8"):
            ch = chr(byte)
            if byte >= 0x80:
                literal.append(f"\\x{byte:02X}")
                after_hex = True
                continue
            if after_hex and ch in "0123456789abcdefABCDEF":
                out.append('"' + "".join(literal) + '"')
                literal = []
            after_hex = False
            literal.append({"\\": "\\\\", '"': '\\"', "\n": "\\n"}.get(ch, ch))
        out.append('"' + "".join(literal) + '"')
        pieces.append(" ".join(out))
    return " ".join(pieces) if pieces else '""'


def header(languages: list[dict]) -> str:
    english, notes = languages[0]["strings"], languages[0]["notes"]
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        f"/* {NOTICE} */",
        "",
        "#ifndef FURNACE_HMI_UI_STRING_IDS_H",
        "#define FURNACE_HMI_UI_STRING_IDS_H",
        "",
        "/** Stable identifiers of the visible strings (catalogue/en.json order). */",
        "typedef enum {",
    ]
    for index, key in enumerate(english):
        if key in notes:
            lines.append(f"    /* {notes[key]} */")
        lines.append(f"    FURNACE_HMI_UI_STRING_{key}{' = 0' if index == 0 else ''},")
    lines += [
        "    FURNACE_HMI_UI_STRING_COUNT",
        "} furnace_hmi_ui_string_id_t;",
        "",
        "/** Languages with a catalogue; the first is the default and the fallback. */",
        "typedef enum {",
    ]
    for index, language in enumerate(languages):
        name = language["tag"].replace("-", "_").upper()
        lines.append(f"    FURNACE_HMI_UI_LANGUAGE_{name}{' = 0' if index == 0 else ''},")
    lines += [
        "    FURNACE_HMI_UI_LANGUAGE_COUNT",
        "} furnace_hmi_ui_language_t;",
        "",
        "#endif /* FURNACE_HMI_UI_STRING_IDS_H */",
        "",
    ]
    return "\n".join(lines)


def c_source(languages: list[dict]) -> str:
    english = languages[0]["strings"]
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        f"/* {NOTICE} */",
        "",
        "#include <inttypes.h>",
        "#include <stddef.h>",
        "",
        '#include "ui_strings_internal.h"',
        "",
    ]
    for language in languages:
        symbol = language["tag"].replace("-", "_").lower()
        lines.append(f"/* {language['tag']}: {len(language['strings'])} of {len(english)} strings; "
                     "missing entries are NULL and fall back to English. */")
        lines.append(f"static const char *const strings_{symbol}[FURNACE_HMI_UI_STRING_COUNT] = {{")
        for key in english:
            if key in language["strings"]:
                lines.append(f"    [FURNACE_HMI_UI_STRING_{key}] = {c_literal(language['strings'][key])},")
        lines += ["};", ""]
    lines.append("const furnace_hmi_ui_language_info_t "
                 "furnace_hmi_ui_language_catalogue[FURNACE_HMI_UI_LANGUAGE_COUNT] = {")
    for language in languages:
        symbol = language["tag"].replace("-", "_")
        lines.append(f"    [FURNACE_HMI_UI_LANGUAGE_{symbol.upper()}] = "
                     f"{{ \"{language['tag']}\", {c_literal(language['name'])}, strings_{symbol.lower()} }},")
    lines += ["};", ""]
    return "\n".join(lines)


def web_block(languages: list[dict]) -> str:
    names = ",".join(f"{{tag:{json.dumps(lang['tag'])},name:{json.dumps(lang['name'])}}}" for lang in languages)
    tables = ",".join(f"{json.dumps(lang['tag'])}:{json.dumps(lang['strings'], ensure_ascii=True, separators=(',', ':'))}"
                      for lang in languages)
    return "\n".join([
        BEGIN,
        "<script id='hmi-strings'>",
        f"const HMI_LANGUAGES=[{names}];",
        f"const HMI_STRINGS={{{tables}}};",
        "</script>",
        END,
    ])


def write(path: Path, text: str, check: bool, stale: list[Path]) -> None:
    current = path.read_bytes().decode("utf-8") if path.exists() else None
    if current == text:
        return
    if check:
        stale.append(path)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    print(f"wrote {path.relative_to(ROOT)}")


def update_page(path: Path, block: str, check: bool, stale: list[Path]) -> None:
    page = path.read_bytes().decode("utf-8")
    start, end = page.find(BEGIN), page.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{path.relative_to(ROOT)}: hmi-strings markers not found")
    write(path, page[:start] + block + page[end + len(END):], check, stale)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    languages = load()
    stale: list[Path] = []
    write(HEADER, header(languages), args.check, stale)
    write(C_SOURCE, c_source(languages), args.check, stale)
    block = web_block(languages)
    for page in WEB_PAGES:
        update_page(page, block, args.check, stale)
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
